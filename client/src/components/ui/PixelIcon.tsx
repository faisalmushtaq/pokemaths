export interface PixelIconProps {
  name: PixelIconName;
  size?: string | number;
  color?: string;
  title?: string;
  className?: string;
  style?: CSSProperties;
}

/** A compact inline sprite rendered as a crisp, single-colour pixel icon. */
export function PixelIcon({ name, size = '1em', color = 'currentColor', title, className, style }: PixelIconProps) {
  const pixels = PIXELS[name];
  return (
    <svg
      viewBox="0 0 8 8"
      width={size}
      height={size}
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      focusable="false"
      className={className}
      style={{ display: 'inline-block', flexShrink: 0, verticalAlign: '-0.13em', color, shapeRendering: 'crispEdges', ...style }}
    >
      {pixels.flatMap((row, y) => Array.from(row).flatMap((value, x) => value === '1'
        ? [<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" />]
        : []))}
    </svg>
  );
}

export function PixelIconLabel({
  name,
  children,
  color,
  size = '0.9em',
  gap = '0.38em',
}: {
  name: PixelIconName;
  children: ReactNode;
  color?: string;
  size?: string | number;
  gap?: string;
}) {
  return <span style={{ display: 'inline-flex', alignItems: 'center', gap, color }}><PixelIcon name={name} size={size} />{children}</span>;
}
